import { type Cue, type CueLine, type TextRun,type ConvertOptions, DEFAULT_OPTIONS } from '../types';
import { msToAssTime } from '../time';
import { hexToAssColor } from '../assColor';

/**
 * Escapes literal braces in ASS text so they are not interpreted as override blocks.
 * @param s - Plain text
 * @returns Escaped text with braces replaced by fullwidth equivalents
 */
function escapeAssText(s: string): string {
  // ASS has no general escaping mechanism; braces would be interpreted as
  // override blocks, so neutralize any literal braces coming from source text.
  return s.replace(/\{/g, '\uFF5B').replace(/\}/g, '\uFF5D');
}

/**
 * Renders the ASS override tags needed to transition from one run's style to the next.
 * @param prev - Previous run's style, or `undefined` for the first run
 * @param run - Current run to emit
 * @returns ASS override block string (e.g. `{\b1\c&H...&}`) or empty string if no change
 */
function renderRunOverrides(prev: TextRun | undefined, run: TextRun): string {
  const tags: string[] = [];
  const prevBold = !!prev?.bold;
  const prevItalic = !!prev?.italic;
  const prevUnderline = !!prev?.underline;
  const prevStrikeout = !!prev?.strikeout;
  const prevColor = prev?.color;

  if (!!run.bold !== prevBold) tags.push(`\\b${run.bold ? 1 : 0}`);
  if (!!run.italic !== prevItalic) tags.push(`\\i${run.italic ? 1 : 0}`);
  if (!!run.underline !== prevUnderline) tags.push(`\\u${run.underline ? 1 : 0}`);
  if (!!run.strikeout !== prevStrikeout) tags.push(`\\s${run.strikeout ? 1 : 0}`);
  if (run.color !== prevColor) {
    tags.push(run.color ? `\\c${hexToAssColor(run.color)}` : `\\c&HFFFFFF&`);
  }
  return tags.length ? `{${tags.join('')}}` : '';
}

/**
 * Renders a single cue line to ASS text with inline override tags.
 * @param line - Cue line to render
 * @returns ASS-formatted line text
 */
function renderLine(line: CueLine): string {
  let out = '';
  let prev: TextRun | undefined;
  for (const run of line.runs) {
    out += renderRunOverrides(prev, run);
    out += escapeAssText(run.text);
    prev = run;
  }
  // Close any still-open styling at the end of the line for cleanliness
  // using ASS's own reset tag, even though ASS resets override state
  // automatically at the next Dialogue event anyway.
  if (prev && (prev.bold || prev.italic || prev.underline || prev.strikeout || prev.color)) {
    out += '{\\r}';
  }
  return out;
}

/**
 * Renders all lines of a cue joined by the ASS hard-break marker `\N`.
 * @param cue - Cue to render
 * @returns ASS text field value
 */
function renderCueText(cue: Cue): string {
  return cue.lines.map(renderLine).join('\\N');
}

const HEADER = (styleName: string) => `[Script Info]
; Generated by subtitle-converter
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.601
PlayResX: 384
PlayResY: 288

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: ${styleName},Arial,20,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,0,2,10,10,10,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

/**
 * Serializes cues to ASS/SSA format.
 * @param cues - Cues to serialize
 * @param options - Serialization options (`defaultAssStyleName` controls the Style name)
 * @returns Complete ASS file content including header and Dialogue lines
 */
export function serializeAss(cues: Cue[], options: ConvertOptions = {}): string {
  const opts = { ...DEFAULT_OPTIONS, ...options };
  const styleName = opts.defaultAssStyleName;
  const lines = cues.map((cue) => {
    const style = cue.styleName || styleName;
    const text = renderCueText(cue);
    return `Dialogue: 0,${msToAssTime(cue.start)},${msToAssTime(cue.end)},${style},,0,0,0,,${text}`;
  });
  return HEADER(styleName) + lines.join('\n') + '\n';
}
